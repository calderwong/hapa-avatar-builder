/** Deterministic ESM wrapper of retained, hash-pinned classic native source.
 * No eval, injected scripts, player, audio, embedded songs or host-global exports.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(await fs.readFile(path.join(root,'resources/living-light-109/manifest.json'),'utf8'));
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const globals=manifest.privateGlobals;
let output='// Generated by scripts/build-living-light-native.mjs. Edit retained named vendor modules through a reviewed source revision.\n';
output+='// Source and module-specific notices: resources/living-light-109/NOTICE.md and credits/SHADER_CREDITS.md.\n';
output+='export function createNativeNamespace() {\nconst window = Object.create(null);\nconst module = undefined; // Disable inherited CommonJS export fallback inside the private ESM host.\nlet '+globals.join(',')+';\n';
for(const name of manifest.runtimeOrder){
 const source=await fs.readFile(path.join(root,'src/living-light/vendor',name));
 if(sha(source)!==manifest.modules.find(m=>m.path===name)?.sha256)throw Error('Vendor hash mismatch: '+name);
 let text=source.toString('utf8');
 // Assignment-only rewriting leaves all other bytes, shader strings and references intact.
 text=text.replace(/window\.([A-Za-z_$][\w$]*)\s*=(?!=)/g,(_,id)=>{
  if(!globals.includes(id))throw Error('Unregistered global: '+id);
  return `${id}=window.${id}=`;
 });
 output+='\n// BEGIN '+name+'\n'+text+'\n// END '+name+'\n';
}
output+='\nreturn Object.freeze(window);\n}\n';
const target=path.join(root,'src/living-light/native.generated.js');
if(process.argv.includes('--check')){if(await fs.readFile(target,'utf8')!==output)throw Error('Native generated file is stale');}
else await fs.writeFile(target,output);
console.log(JSON.stringify({modules:manifest.runtimeOrder.length,bytes:Buffer.byteLength(output),sha256:sha(output)}));
